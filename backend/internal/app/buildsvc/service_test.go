func TestDelete_ProtectsTeamUsedBuilds(t *testing.T) {
	db := openTestDB(t)

	users := sqlite.NewUserRepo(db)
	accounts := sqlite.NewAccountRepo(db)
	builds := sqlite.NewBuildRepo(db)
	teams := sqlite.NewTeamRepo(db)
	svc := New(builds, accounts)
	teamSvc := teamsvc.New(teams, builds, accounts)

	ctx := context.Background()
	owner := &domain.User{DiscordID: "del-owner", Username: "o"}
	if err := users.Create(ctx, owner); err != nil {
		t.Fatalf("seed failed: %v", err)
	}
	ownerID := owner.ID

	account := &domain.GameAccount{UserID: ownerID, UID: "1504699999"}
	if err := accounts.Create(ctx, account); err != nil {
		t.Fatalf("seed failed: %v", err)
	}

	free, err := svc.Create(ctx, CreateInput{
		UserID: ownerID, GameAccountID: account.ID, Name: "Free",
		RawAgentPayload: fairyAgentJSON(t, 1511, "Miyabi", false),
		RawData:         sampleRawAvatar(1511),
	})
	if err != nil {
		t.Fatalf("create failed: %v", err)
	}
	used, err := svc.Create(ctx, CreateInput{
		UserID: ownerID, GameAccountID: account.ID, Name: "Used",
		RawAgentPayload: fairyAgentJSON(t, 1411, "Ellen", false),
		RawData:         sampleRawAvatar(1411),
	})
	if err != nil {
		t.Fatalf("create failed: %v", err)
	}

	if _, err := teamSvc.Create(ctx, teamsvc.CreateInput{
		UserID: ownerID, GameAccountID: account.ID, Name: "T",
		BuildIDs: []uuid.UUID{used.ID},
	}); err != nil {
		t.Fatalf("team create failed: %v", err)
	}

	if err := svc.Delete(ctx, ownerID, used.ID); !errors.Is(err, domain.ErrConflict) {
		t.Errorf("expected ErrConflict deleting team-used build, got %v", err)
	}
	if err := svc.Delete(ctx, ownerID, free.ID); err != nil {
		t.Errorf("expected free build deletion to succeed, got %v", err)
	}
	if err := svc.Delete(ctx, ownerID, free.ID); !errors.Is(err, domain.ErrNotFound) {
		t.Errorf("expected ErrNotFound on double delete, got %v", err)
	}
}

