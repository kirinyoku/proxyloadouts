func TestService_UpdateDescription(t *testing.T) {
	env := newFixture(t)
	ctx := context.Background()

	rawAvatarBytes, _ := json.Marshal(zzz.AvatarData{ID: 1511})
	build, err := env.svc.Create(ctx, CreateInput{
		UserID:          env.ownerID,
		GameAccountID:   env.accountID,
		Name:            "Original Name",
		RawAgentPayload: fairyAgentJSON(t, 1511, "Miyabi", false),
		RawData:         rawAvatarBytes,
	})
	if err != nil {
		t.Fatalf("Create failed: %v", err)
	}

	// 1. Update description while preserving original name
	desc := "New build description"
	if err := env.svc.UpdateDescription(ctx, env.ownerID, build.ID, &desc); err != nil {
		t.Fatalf("UpdateDescription failed: %v", err)
	}

	updated, err := env.svc.Get(ctx, env.ownerID, build.ID)
	if err != nil {
		t.Fatalf("Get failed: %v", err)
	}
	if updated.Name != "Original Name" {
		t.Errorf("expected name to stay 'Original Name', got %q", updated.Name)
	}
	if updated.Description == nil || *updated.Description != "New build description" {
		t.Errorf("expected description 'New build description', got %v", updated.Description)
	}

	// 2. Clear description by passing nil
	if err := env.svc.UpdateDescription(ctx, env.ownerID, build.ID, nil); err != nil {
		t.Fatalf("UpdateDescription(nil) failed: %v", err)
	}
	cleared, err := env.svc.Get(ctx, env.ownerID, build.ID)
	if err != nil {
		t.Fatalf("Get after clear failed: %v", err)
	}
	if cleared.Description != nil {
		t.Errorf("expected description to be nil, got %v", cleared.Description)
	}

	// 3. Foreign user cannot update description
	if err := env.svc.UpdateDescription(ctx, env.foreignID, build.ID, &desc); !errors.Is(err, domain.ErrForbidden) {
		t.Errorf("expected ErrForbidden for foreign user, got %v", err)
	}

	// 4. Exceeding max description length returns ErrInvalidInput
	tooLong := strings.Repeat("x", domain.MaxBuildDescriptionLength+1)
	if err := env.svc.UpdateDescription(ctx, env.ownerID, build.ID, &tooLong); !errors.Is(err, domain.ErrInvalidInput) {
		t.Errorf("expected ErrInvalidInput for description too long, got %v", err)
	}
}

