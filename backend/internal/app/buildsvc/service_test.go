// openTestDB returns a migrated SQLite database backed by a temp file.
func openTestDB(t *testing.T) *sql.DB {
	t.Helper()

	db, err := sqlite.NewDB(filepath.Join(t.TempDir(), "builds.db"))
	if err != nil {
		t.Fatalf("failed to open db: %v", err)
	}
	t.Cleanup(func() { _ = db.Close() })
	if err := sqlite.Migrate(context.Background(), db); err != nil {
		t.Fatalf("failed to migrate db: %v", err)
	}
	return db
}

// fixtureEnv bundles migrated repos and seeded owner/foreign identities.
