func TestCreate_ValidationErrors(t *testing.T) {
	env := newFixture(t)
	ctx := context.Background()

	cases := []struct {
		name string
		in   CreateInput
		want error
	}{
		{"invalid payload", CreateInput{UserID: env.ownerID, GameAccountID: env.accountID,
			RawAgentPayload: json.RawMessage(`{not-json`)}, domain.ErrInvalidInput},
		{"missing agent id", CreateInput{UserID: env.ownerID, GameAccountID: env.accountID,
			RawAgentPayload: json.RawMessage(`{"name":"Miyabi"}`)}, domain.ErrInvalidInput},
		{"empty payload", CreateInput{UserID: env.ownerID, GameAccountID: env.accountID,
			RawAgentPayload: nil}, domain.ErrInvalidInput},
		{"unknown account", CreateInput{UserID: env.ownerID, GameAccountID: uuid.New(),
			RawAgentPayload: fairyAgentJSON(t, 1511, "Miyabi", true)}, domain.ErrNotFound},
		{"foreign account", CreateInput{UserID: env.foreignID, GameAccountID: env.accountID,
			RawAgentPayload: fairyAgentJSON(t, 1511, "Miyabi", true)}, domain.ErrForbidden},
		{"missing user", CreateInput{GameAccountID: env.accountID,
			RawAgentPayload: fairyAgentJSON(t, 1511, "Miyabi", true)}, domain.ErrInvalidInput},
	}
	for _, tc := range cases {
		if _, err := env.svc.Create(ctx, tc.in); !errors.Is(err, tc.want) {
			t.Errorf("%s: expected %v, got %v", tc.name, tc.want, err)
		}
	}
}

