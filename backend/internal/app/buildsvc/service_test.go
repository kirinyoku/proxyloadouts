	foreignAgentPayload := fairyAgentJSON(t, 1061, "Clara", false)
	_, err = svcWithScanner.Create(ctx, CreateInput{
		UserID:          env.ownerID,
		GameAccountID:   env.accountID,
		Name:            "Foreign Agent",
		RawAgentPayload: foreignAgentPayload,
	})
	if !errors.Is(err, domain.ErrInvalidInput) {
		t.Errorf("expected ErrInvalidInput for agent not in showcase, got %v", err)
	}

	// 3. Reject agent with weapon UID mismatch
	mismatchedWeaponPayload := map[string]any{
		"id":   1511,
		"name": "Miyabi",
		"w_engine": map[string]any{
			"id":  14109,
			"uid": "different_weapon_uid",
		},
	}
