package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/kirinyoku/fairy"
)

func findRepoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "frontend", "package.json")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	return "", errors.New("could not find repo root containing frontend/package.json")
}

func main() {
	repoRoot, err := findRepoRoot()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error locating repository root: %v\n", err)
		os.Exit(1)
	}

	targetPath := filepath.Join(repoRoot, "frontend", "src", "lib", "game-constants.generated.ts")

	var buf bytes.Buffer
	buf.WriteString(`// Code generated by backend/cmd/codegen from github.com/kirinyoku/fairy. DO NOT EDIT.

/**
 * Every supported combat specialty from the fairy SDK.
 */
export const ALL_SPECIALTIES = [
`)

	specialties := fairy.AllSpecialties()
	for _, s := range specialties {
		fmt.Fprintf(&buf, "\t'%s',\n", s)
	}
	buf.WriteString(`] as const

export type Specialty = (typeof ALL_SPECIALTIES)[number]

/**
 * Official Enka Network CDN icons for combat specialties, from fairy.
 */
export const SPECIALTY_ICONS: Record<Specialty, string> = {
`)
	for _, s := range specialties {
		fmt.Fprintf(&buf, "\t%s: '%s',\n", s, s.IconURL())
	}
	buf.WriteString(`}

/**
 * Every supported elemental attribute from the fairy SDK.
 */
export const ALL_ATTRIBUTES = [
`)

	attributes := fairy.AllAttributes()
	for _, a := range attributes {
		fmt.Fprintf(&buf, "\t'%s',\n", a)
	}
	buf.WriteString(`] as const

export type Attribute = (typeof ALL_ATTRIBUTES)[number]

/**
 * Every supported rarity rank from the fairy SDK.
 */
export const ALL_RARITIES = [
`)

	rarities := fairy.AllRarities()
	for _, r := range rarities {
		fmt.Fprintf(&buf, "\t'%s',\n", r)
	}
	buf.WriteString(`] as const

export type Rarity = (typeof ALL_RARITIES)[number]

/**
 * Official Enka Network CDN icons for rarity ranks, from fairy.
 */
export const RARITY_ICONS: Record<Rarity, string> = {
`)
	for _, r := range rarities {
		fmt.Fprintf(&buf, "\t%s: '%s',\n", r, r.IconURL())
	}
	buf.WriteString("}\n\n")

	buf.WriteString(`/**
 * Recommended agent combat stats (HighlightProps) from the fairy SDK.
 * The game highlights these in yellow on the agent stats screen.
 */
export const AGENT_HIGHLIGHT_PROPS: Record<number, readonly number[]> = {
`)
	allAgentProps := fairy.AllAgentHighlightProps()
	agentIDs := make([]int, 0, len(allAgentProps))
	for id := range allAgentProps {
		agentIDs = append(agentIDs, id)
	}
	sort.Ints(agentIDs)

	for _, id := range agentIDs {
		props := allAgentProps[id]
		propStrs := make([]string, len(props))
		for i, p := range props {
			propStrs[i] = strconv.Itoa(int(p))
		}
		fmt.Fprintf(&buf, "\t%d: [%s],\n", id, strings.Join(propStrs, ", "))
	}
	buf.WriteString("}\n\n")

	buf.WriteString(`/**
 * Recommended agent drive disc sub-stats (RecommendedSubStats) from the fairy SDK.
 * The game highlights these in yellow on the drive disc card.
 */
export const AGENT_RECOMMENDED_SUBSTATS: Record<number, readonly number[]> = {
`)
	allAgentSubstats := fairy.AllAgentRecommendedSubStats()
	substatAgentIDs := make([]int, 0, len(allAgentSubstats))
	for id := range allAgentSubstats {
		substatAgentIDs = append(substatAgentIDs, id)
	}
	sort.Ints(substatAgentIDs)

	for _, id := range substatAgentIDs {
		substats := allAgentSubstats[id]
		strs := make([]string, len(substats))
		for i, p := range substats {
			strs[i] = strconv.Itoa(int(p))
		}
		fmt.Fprintf(&buf, "\t%d: [%s],\n", id, strings.Join(strs, ", "))
	}
	buf.WriteString("}\n")

	if err := os.WriteFile(targetPath, buf.Bytes(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "Failed to write generated file to %s: %v\n", targetPath, err)
		os.Exit(1)
	}

	fmt.Printf("Successfully generated game constants at %s\n", targetPath)
}
