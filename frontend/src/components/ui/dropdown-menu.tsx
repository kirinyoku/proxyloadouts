        "relative flex cursor-pointer items-center rounded-xl py-1.5 pr-2.5 pl-8 text-xs font-mono font-medium outline-none select-none transition-colors hover:bg-white/[0.08] hover:text-foreground focus:bg-white/[0.08] focus:text-foreground data-disabled:pointer-events-none data-disabled:opacity-40",
        className
